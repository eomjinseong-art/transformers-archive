export function getCar(slug: string) {
  return cars.find((car) => car.slug === slug);
}

export function carsForFilm(filmSlug: string) {
  return cars.filter((car) => car.filmSlugs.includes(filmSlug));
}

export function sameBrandCars(car: TfCar) {
  const brands = new Set([car.brand, ...(car.relatedBrands ?? [])]);
  return cars.filter(
    (other) =>
      other.slug !== car.slug &&
      (brands.has(other.brand) || (other.relatedBrands ?? []).some((b) => b === car.brand)),
  );
}

export function brandsWithCars() {
  const map = new Map<string, { brand: string; brandKo: string; cars: TfCar[] }>();
  for (const car of cars) {
    const entry = map.get(car.brand) ?? { brand: car.brand, brandKo: car.brandKo, cars: [] };
    entry.cars.push(car);
    map.set(car.brand, entry);
  }
  return [...map.values()].sort((a, b) => b.cars.length - a.cars.length || a.brandKo.localeCompare(b.brandKo, "ko"));
}

export function brandSlug(brand: string) {
  return brand
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
